create table public.autos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  marca text,
  modelo text,
  precio numeric
);

alter table public.autos enable row level security;

create policy "select es publico" on public.autos
  for select using (true);

create policy "anonimos escriben (sólo para practicar)" on public.autos
  for all to anon using (true) with check (true);

alter publication supabase_realtime add table public.autos;
