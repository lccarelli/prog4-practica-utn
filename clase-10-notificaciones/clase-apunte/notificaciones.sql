create table public.suscripciones_notificaciones (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  endpoint text not null,
  auth text not null,
  p256dh text not null unique
);

alter table public.suscripciones_notificaciones enable row level security;

create policy "anonimos se suscriben" on public.suscripciones_notificaciones
  for insert to anon with check (true);
